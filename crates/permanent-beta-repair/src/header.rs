//! Offsets header (design §7.2): `hooks.gen.h`, the hooks' RVAs and patterns per build, for hook DLLs that
//! select their targets from a hardcoded table instead of reading a manifest at run time.
//!
//! Built from one or more manifests (typically every repaired manifest of a release line). A hook gets an
//! entry for a build only where some manifest has a locator bound to that build: a hook repair left in review
//! has RVA 0 there, so a DLL using the table can't patch it by accident. Trial bindings are refused.

use permanent_beta_model::{BuildId, HookManifest, Rva};
use std::collections::BTreeMap;

#[derive(Debug, Clone, PartialEq, Eq)]
struct Entry {
    rva: Rva,
    pattern: Option<String>,
}

/// The C header text, or why the manifests can't make one (conflicting locators, a trial binding, a hook name
/// that isn't a usable identifier).
pub fn offsets_header(manifests: &[HookManifest]) -> Result<String, String> {
    let mut hooks: Vec<String> = Vec::new();
    let mut builds: Vec<BuildId> = Vec::new();
    let mut table: BTreeMap<(BuildId, String), Entry> = BTreeMap::new();

    for m in manifests {
        for h in &m.hooks {
            if h.trial {
                return Err(format!(
                    "hook {} is a trial binding (pbeta repair --trial-out); a header must only carry verified \
                     locators",
                    h.name
                ));
            }
            if !hooks.contains(&h.name) {
                hooks.push(h.name.clone());
            }
            let Some(rva) = h.target.rva else { continue };
            if u32::try_from(rva.0).is_err() {
                return Err(format!("hook {}: RVA {rva} doesn't fit 32 bits", h.name));
            }
            let b = h.target.build.clone();
            if !builds.contains(&b) {
                builds.push(b.clone());
            }
            let entry = Entry {
                rva,
                pattern: h.target.pattern.clone(),
            };
            match table.get(&(b.clone(), h.name.clone())) {
                Some(existing) if *existing != entry => {
                    return Err(format!(
                        "hook {}: two manifests disagree about build {} ({} vs {})",
                        h.name, b.0, existing.rva, entry.rva
                    ));
                }
                _ => {
                    table.insert((b, h.name.clone()), entry);
                }
            }
        }
    }

    let idents: Vec<String> = hooks.iter().map(|h| ident(h)).collect();
    for (i, id) in idents.iter().enumerate() {
        if id.is_empty() || id.starts_with(|c: char| c.is_ascii_digit()) {
            return Err(format!("hook {:?} has no usable C identifier", hooks[i]));
        }
        if idents[..i].contains(id) {
            return Err(format!(
                "hooks {:?} and {:?} map to the same C identifier {id}",
                hooks[idents.iter().position(|x| x == id).unwrap_or(0)],
                hooks[i]
            ));
        }
    }

    let mut out = String::new();
    out.push_str(
        "/* hooks.gen.h: generated by `pbeta header` from hook manifests. Do not edit.\n\
         *\n\
         * Per build (SHA-256 of the executable, lowercase hex), each hook's RVA and AOB pattern. RVA 0 means the\n\
         * hook has no verified locator for that build (it is unresolved or waiting in review): don't patch it.\n\
         * A NULL pattern means none was generated or none is unique. */\n\
         #pragma once\n\
         #include <stddef.h>\n\
         #include <stdint.h>\n\
         #include <string.h>\n\n",
    );
    out.push_str(&format!("#define PBETA_HOOK_COUNT {}\n\n", hooks.len()));
    out.push_str("enum pbeta_hook {\n");
    for (i, id) in idents.iter().enumerate() {
        out.push_str(&format!(
            "    PBETA_HOOK_{} = {i},\n",
            id.to_ascii_uppercase()
        ));
    }
    out.push_str("};\n\n");
    out.push_str("static const char* const pbeta_hook_names[PBETA_HOOK_COUNT] = {\n");
    for h in &hooks {
        out.push_str(&format!("    {},\n", c_string(h)));
    }
    out.push_str("};\n\n");
    out.push_str(
        "typedef struct pbeta_build_offsets {\n\
         \x20   const char* sha256;\n\
         \x20   uint32_t rva[PBETA_HOOK_COUNT];\n\
         \x20   const char* pattern[PBETA_HOOK_COUNT];\n\
         } pbeta_build_offsets;\n\n",
    );
    out.push_str(&format!("#define PBETA_BUILD_COUNT {}\n\n", builds.len()));
    out.push_str("static const pbeta_build_offsets pbeta_builds[PBETA_BUILD_COUNT] = {\n");
    for b in &builds {
        let entries: Vec<Option<&Entry>> = hooks
            .iter()
            .map(|h| table.get(&(b.clone(), h.clone())))
            .collect();
        let rvas: Vec<String> = entries
            .iter()
            .map(|e| e.map_or("0".to_owned(), |e| e.rva.to_string()))
            .collect();
        let patterns: Vec<String> = entries
            .iter()
            .map(|e| {
                e.and_then(|e| e.pattern.as_deref())
                    .map_or("NULL".to_owned(), c_string)
            })
            .collect();
        out.push_str(&format!(
            "    {{\n        {},\n        {{{}}},\n        {{{}}},\n    }},\n",
            c_string(&b.0.to_ascii_lowercase()),
            rvas.join(", "),
            patterns.join(", ")
        ));
    }
    out.push_str("};\n\n");
    out.push_str(
        "/* The offsets for the running build, or NULL if this header doesn't know it. */\n\
         static inline const pbeta_build_offsets* pbeta_find_build(const char* sha256) {\n\
         \x20   for (size_t i = 0; i < PBETA_BUILD_COUNT; i++) {\n\
         \x20       if (strcmp(pbeta_builds[i].sha256, sha256) == 0) {\n\
         \x20           return &pbeta_builds[i];\n\
         \x20       }\n\
         \x20   }\n\
         \x20   return NULL;\n\
         }\n",
    );
    Ok(out)
}

fn ident(name: &str) -> String {
    name.chars()
        .map(|c| if c.is_ascii_alphanumeric() { c } else { '_' })
        .collect()
}

/// A C string literal. `?` is escaped so `??` in a pattern can never form a trigraph.
fn c_string(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '?' => out.push_str("\\?"),
            c if c.is_ascii_graphic() || c == ' ' => out.push(c),
            c => out.push_str(&format!("\\x{:02x}", c as u32 & 0xff)),
        }
    }
    out.push('"');
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use permanent_beta_model::{Criticality, HookSpec, TargetLocator};

    fn hook(name: &str, build: &str, rva: u64, pattern: Option<&str>) -> HookSpec {
        HookSpec {
            name: name.into(),
            detour: None,
            criticality: Criticality::Normal,
            prototype: None,
            trial: false,
            target: TargetLocator {
                build: BuildId(build.into()),
                rva: Some(Rva(rva)),
                symbol: None,
                pattern: pattern.map(Into::into),
            },
        }
    }

    fn manifest(hooks: Vec<HookSpec>) -> HookManifest {
        HookManifest { hooks }
    }

    #[test]
    fn one_row_per_build_with_review_hooks_at_zero() {
        let v1 = manifest(vec![
            hook("price_lookup", "AA", 0x1010, Some("48 8B ?? 05")),
            hook("log_event", "AA", 0x1000, None),
        ]);
        // v2: log_event went to review, so its locator is still bound to v1.
        let v2 = manifest(vec![
            hook("price_lookup", "BB", 0x1080, None),
            hook("log_event", "AA", 0x1000, None),
        ]);
        let h = offsets_header(&[v1, v2]).unwrap();
        assert!(h.contains("#define PBETA_HOOK_COUNT 2"), "{h}");
        assert!(h.contains("PBETA_HOOK_PRICE_LOOKUP = 0,"), "{h}");
        assert!(h.contains("#define PBETA_BUILD_COUNT 2"), "{h}");
        assert!(h.contains("\"aa\",\n        {0x1010, 0x1000},"), "{h}");
        assert!(h.contains("\"bb\",\n        {0x1080, 0},"), "{h}");
        // Wildcards are escaped: no trigraphs.
        assert!(h.contains(r#""48 8B \?\? 05""#), "{h}");
        assert!(!h.contains("??"), "{h}");
    }

    #[test]
    fn conflicting_locators_and_trial_bindings_are_refused() {
        let a = manifest(vec![hook("f", "AA", 0x1010, None)]);
        let b = manifest(vec![hook("f", "AA", 0x1020, None)]);
        assert!(
            offsets_header(&[a.clone(), b])
                .unwrap_err()
                .contains("disagree")
        );

        let mut trial = a.clone();
        trial.hooks[0].trial = true;
        assert!(offsets_header(&[trial]).unwrap_err().contains("trial"));

        let clash = manifest(vec![hook("a-b", "AA", 1, None), hook("a_b", "AA", 2, None)]);
        assert!(offsets_header(&[clash]).is_err());
    }
}
